FONT_BODY = '仿宋_GB2312'
FONT_HEAD = '黑体'
FONT_MONO = 'Consolas'


def set_run_font(run, name, size_pt, bold=False):
    run.font.name = name
    run.font.size = Pt(size_pt)
    run.bold = bold
    rpr = run._element.get_or_add_rPr()
    rFonts = rpr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = rpr.makeelement(qn('w:rFonts'), {})
        rpr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), name)


def add_title(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(18)
    r = p.add_run(text)
    set_run_font(r, FONT_HEAD, 22, bold=True)
    return p


def add_h1(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(10)
    r = p.add_run(text)
    set_run_font(r, FONT_HEAD, 16, bold=True)
    return p


def add_h2(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text)
    set_run_font(r, FONT_HEAD, 14, bold=True)
    return p


def add_body(doc, runs):
    """runs: list of (text, bold) tuples"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    for text, bold in runs:
        r = p.add_run(text)
        set_run_font(r, FONT_BODY, 12, bold=bold)
    return p


def add_note(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text)
    set_run_font(r, FONT_BODY, 10.5, bold=False)
    return p


def add_image(doc, path, width_inches, caption=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run()
    run.add_picture(path, width=Inches(width_inches))
    if caption:
        add_note(doc, caption)


def add_placeholder(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(10)
    r = p.add_run(text)
    set_run_font(r, FONT_BODY, 11, bold=True)
    return p


def add_mono_block(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(10)
    lines = text.split('\n')
    for i, line in enumerate(lines):
        if i > 0:
            p.add_run().add_break()
        r = p.add_run(line)
        set_run_font(r, FONT_MONO, 10, bold=False)
    return p


def add_bullet(doc, runs):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(8)
    for text, bold in runs:
        r = p.add_run(text)
        set_run_font(r, FONT_BODY, 12, bold=bold)
    return p


def add_table(doc, header, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = 'Table Grid'
    for j, h in enumerate(header):
        cell = t.rows[0].cells[j]
        p = cell.paragraphs[0]
        r = p.add_run(h)
        set_run_font(r, FONT_BODY, 11, bold=True)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            p = cell.paragraphs[0]
            r = p.add_run(val)
            set_run_font(r, FONT_BODY, 11, bold=False)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


